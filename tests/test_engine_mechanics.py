"""U100: Rules-as-implemented tests for the engine forward model.

The engine's behavior (not printed card text) is the authoritative rulebook.
These tests probe specific mechanics via the cg.api interface to pin down how
the engine actually interprets the game rules, and assert on REAL, concrete
values observed on the live engine -- not structural placeholders.

Mechanics tested:
- Damage calculation (base damage, weakness, resistance)
- Energy requirements and retreat costs
- Status effects (poison, burn, sleep, paralyze, confuse)
- Prize flow (knock out, prize take, game end)
- On-evolve ability triggers
- Sub-select semantics (CARD, COUNT, YES_NO)
- Turn structure and action ordering

CHARACTERIZATION METHOD (see tests/engine_state_driver.py's module docstring
for the full write-up of what was learned probing the live engine):

  cg.api.search_begin can only be called with a real Observation extracted
  from a recorded replay (data/replays/*.json) -- its search_begin_input
  token is generated by the native engine and cannot be fabricated, and once
  a replay-derived observation is supplied, the engine reconstructs the TRUE
  hidden board state behind it (your_deck/opponent_deck arguments are
  cosmetic for the already-revealed board). That means most of these
  mechanics cannot be pinned to a single hand-picked matchup; instead
  tests/engine_state_driver.py drives many real replay-seeded games forward
  with a deliberate policy (prefer a status-inflicting attack, else any
  attack, else evolve, else attach energy, else play a card -- never blindly
  "first legal") and MINES the resulting games for concrete, naturally
  occurring evidence of each mechanic. Every assertion below is grounded in
  that mined evidence (or, for sleep's coin-flip wake-up, a single
  deterministic replay file chosen because it reliably reproduces the
  mechanic). Where a mechanic could not be produced within a realistic
  mining budget (checked against the ENTIRE 1029-replay corpus), the test
  documents that as a pytest.skip with the exact scan performed, rather than
  silently passing.
"""

