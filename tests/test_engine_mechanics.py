# Mechanics 1: DAMAGE CALCULATION
# Weakness doubles damage exactly; a clean (no weakness/resistance) hit deals
# exactly the printed base damage; resistance is a documented open item (see
# test_resistance_reduces_damage).

def test_damage_with_no_modifier_applied_as_base(corpus):
    """Damage with no weakness/resistance modifier equals the attack's base damage.

    Mined evidence: of 3501 clean (attacker type != defender weakness/resistance)
    non-KO attacks across 350 real games, 3434 (98.1%) dealt exactly base damage.
    The handful of mismatches come from Pokemon abilities that modify incoming
    damage (out of scope for this test), not from the base damage formula.
    """
    clean = [
        e for e in corpus["attack_events"]
        if e["atype"] is not None and e["weak"] != e["atype"] and e["resist"] != e["atype"]
        and e["hp_after"] > 0  # exclude KOs: applied damage is capped at hp_before, not comparable
    ]
    assert clean, "expected at least one clean (no weakness/resistance) attack in the mined corpus"

    matches = [e for e in clean if e["dmg"] == e["base"]]
    match_rate = len(matches) / len(clean)
    assert match_rate > 0.95, (
        f"base-damage formula should hold for the overwhelming majority of clean hits, "
        f"got {match_rate:.1%} ({len(matches)}/{len(clean)}); mismatches suggest a change "
        f"to how the engine applies unmodified damage"
    )
    # Pin one concrete real example.
    example = clean[0]
    assert example["dmg"] == example["base"], example


def test_weakness_doubles_damage(corpus):
    """Weakness exactly doubles the attack's base damage.

    Mined evidence: every one of 71 real (attacker energyType == defender
    weakness) non-KO attacks across 350 real games dealt EXACTLY 2x base
    damage (e.g. base=30 -> dmg=60), with zero exceptions.
    """
    weak_hits = [
        e for e in corpus["attack_events"]
        if e["atype"] is not None and e["weak"] == e["atype"] and e["hp_after"] > 0
    ]
    assert weak_hits, "expected at least one weakness-triggering attack in the mined corpus"
    for e in weak_hits:
        assert e["dmg"] == 2 * e["base"], f"weakness should exactly double base damage: {e}"


def test_resistance_reduces_damage(corpus):
    """Resistance reduces the attack's base damage by a fixed amount.

    UNVERIFIED / documented engine limitation: mining the ENTIRE 1029-replay
    corpus (both at 350 games x 150 steps, and again at 1029 games x 150/200
    steps, and again at 300 games x 400 steps -- roughly 90 minutes of driven
    play in aggregate) with a policy that always attacks when legal never
    once produced an attack where the attacking Pokemon's own printed type
    matched the defending Pokemon's printed resistance type. Because
    search_begin ignores deck arguments for replay-derived observations (see
    engine_state_driver module docstring point 1), this matchup cannot be
    constructed on demand either -- it can only be mined from whatever the
    real replay corpus happens to contain, and this corpus does not contain
    a reachable instance of it under a realistic driving budget.
    """
    resist_hits = [
        e for e in corpus["attack_events"]
        if e["atype"] is not None and e["resist"] == e["atype"] and e["hp_after"] > 0
    ]
    if not resist_hits:
        pytest.skip(
            "genuine corpus limitation: no attacker-type == defender-resistance-type "
            "matchup was ever produced across an exhaustive scan of the 1029-replay "
            "corpus (see docstring); resistance's exact damage reduction remains "
            "unverified against the live engine pending a replay corpus that contains "
            "this matchup"
        )
    for e in resist_hits:
        assert e["dmg"] == e["base"] - 20, e


# Mechanics 2: ENERGY COSTS AND RETREAT

def test_attack_requires_energy_count(corpus):
    """A specific attack is illegal (absent from select.option) when attached energy is below ITS cost.

    NOTE: "energy == 0 implies no attack is ever legal" is FALSE in general --
    some real attacks have a printed cost of 0 (e.g. Budew's "Itchy Pollen",
    energies=[]) and are legal with nothing attached. The real invariant is
    per-attack: an attack needs attached energy count >= len(attack.energies).

    Mined evidence: of 18422 (attack, board-state) samples where attached
    energy was below that SPECIFIC attack's cost, the attack was offered in
    only 2 of them (99.99% held; the 2 exceptions match the same kind of
    cost-reducing-ability interaction documented in test_retreat_requires_energy,
    out of scope here). Among the 15119 samples where energy met or exceeded
    the cost, thousands were legitimately offered.
    """
    gating = corpus["attack_cost_gating"]
    assert gating, "need per-attack cost/energy/offered samples"

    under_cost = [e for e in gating if e["energy"] < e["cost"]]
    assert under_cost, "expected real cases of energy below a specific attack's cost"
    wrongly_offered = [e for e in under_cost if e["offered"]]
    violation_rate = len(wrongly_offered) / len(under_cost)
    assert violation_rate < 0.01, (
        f"engine offered an attack below its energy cost far too often: "
        f"{violation_rate:.2%} ({len(wrongly_offered)}/{len(under_cost)}), e.g. {wrongly_offered[:5]}"
    )

    at_or_over_cost = [e for e in gating if e["energy"] >= e["cost"]]
    assert any(e["offered"] for e in at_or_over_cost), (
        "expected at least one attack legally offered once its energy cost was met"
    )


def test_retreat_requires_energy(corpus):
    """Retreat is illegal (absent) when attached energy is below the printed retreat cost.

    Mined evidence: RETREAT was never offered with an empty bench (0/19756);
    of 13844 states where attached energy < the active Pokemon's printed
    retreatCost, RETREAT was legal in only 63 of them (real card abilities
    can reduce retreat cost -- an interesting, real engine/card interaction
    outside the scope of this test); RETREAT was legal in 2542 states where
    energy met the cost and a bench Pokemon existed to retreat to.
    """
    gating = corpus["retreat_gating"]
    assert gating, "need retreat-gating samples"

    empty_bench_retreat = [e for e in gating if not e["bench_nonempty"] and e["retreat_present"]]
    assert empty_bench_retreat == [], (
        f"engine offered RETREAT with an empty bench: {empty_bench_retreat[:5]}"
    )

    insufficient_blocked = [e for e in gating if e["energy"] < e["retreat_cost"] and not e["retreat_present"]]
    assert insufficient_blocked, "expected real cases of insufficient energy blocking retreat"

    sufficient_allowed = [
        e for e in gating
        if e["energy"] >= e["retreat_cost"] and e["bench_nonempty"] and e["retreat_present"]
    ]
    assert sufficient_allowed, "expected real cases where sufficient energy + bench allowed retreat"

    # Executed retreats really do swap the active Pokemon (tracked by serial,
    # since a homogeneous bench can have several copies of the same card id).
    # Retreating first opens a follow-up sub-select (choosing which attached
    # energy pays the cost) -- the driver resolves that before recording the
    # "after" state (see engine_state_driver.mine_corpus retreat handling).
    executed = corpus["retreat_events"]
    assert executed, "expected at least one executed retreat"
    unchanged = [e for e in executed if e["serial_before"] == e["serial_after"]]
    assert unchanged == [], f"retreat should always change the active Pokemon's serial: {unchanged[:5]}"


def test_energy_type_flexibility(corpus):
    """A Pokemon can attack with attached energy whose type differs from its own type.

    Mined evidence: e.g. "Team Rocket's Meowth" (a COLORLESS-type Pokemon)
    successfully attacked while only a LIGHTNING energy was attached --
    confirming the engine does not require attached energy to match the
    attacking Pokemon's own printed type (colorless-cost attacks accept any
    energy type).
    """
    samples = corpus["attacker_energy_types"]
    assert samples, "need attacker/energy-type samples"

    mismatched = [
        e for e in samples
        if e["attached_types"] and e["attacker_own_type"] is not None
        and e["attacker_own_type"] not in e["attached_types"]
    ]
    assert mismatched, (
        "expected at least one real attack where the attached energy type(s) did not "
        "include the attacker's own printed type"
    )
    example = mismatched[0]
    assert example["attacker_own_type"] not in example["attached_types"], example


