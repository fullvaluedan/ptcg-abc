# Mechanics 7: TURN STRUCTURE

def test_turn_counter_increments(corpus):
    """The turn counter is monotonically non-decreasing and never skips by more than 1.

    Mined evidence: 350 real turn-number sequences (one per game), every one
    monotonically non-decreasing, and none ever jumping by more than 1
    between consecutive selects.
    """
    sequences = corpus["turn_sequences"]
    assert sequences, "expected at least one recorded turn sequence"
    non_trivial = [s for s in sequences if len(s) > 1]
    assert non_trivial, "expected at least one game with multiple turn observations"

    for seq in sequences:
        for i in range(len(seq) - 1):
            assert seq[i + 1] >= seq[i], f"turn counter decreased: {seq}"
            assert seq[i + 1] - seq[i] <= 1, f"turn counter skipped a value: {seq}"

    assert any(seq[-1] > seq[0] for seq in non_trivial), "expected the turn counter to actually advance somewhere"


def test_energy_attached_resets_each_turn(corpus):
    """The energyAttached (manual-energy-used-this-turn) flag resets at the start of a player's next turn.

    Mined evidence: of 3013 real (turn_before, energyAttached=True) samples,
    2986 (99.1%) showed energyAttached reset to False by that same player's
    next turn. A small number of exceptions come from card effects that grant
    extra energy attachments in the same turn (out of scope here).
    """
    samples = corpus["energy_attached_resets"]
    assert samples, "expected at least one energyAttached turn-boundary sample"

    was_true = [e for e in samples if e["flag_before"]]
    assert was_true, "expected at least one turn boundary where energyAttached was True"
    reset = [e for e in was_true if not e["flag_after"]]
    reset_rate = len(reset) / len(was_true)
    assert reset_rate > 0.95, (
        f"energyAttached should reset for the overwhelming majority of turn boundaries, "
        f"got {reset_rate:.1%} ({len(reset)}/{len(was_true)})"
    )
    example = reset[0]
    assert example["flag_before"] is True and example["flag_after"] is False, example


def test_attack_once_per_turn(corpus):
    """An attack can be taken only once per turn.

    Mined evidence: of 9051 real attacks, 745 were followed by the SAME
    player still acting within the SAME turn number (i.e. attacking did not
    immediately end their turn). In every one of those 745 cases, ATTACK was
    absent from the very next select's options -- zero exceptions.
    """
    samples = corpus["attack_once_per_turn"]
    assert samples, "expected at least one recorded attack"

    same_turn_continues = [e for e in samples if e["same_turn_continues"]]
    assert same_turn_continues, (
        "expected at least one attack after which the same player's turn continued "
        "(needed to observe whether ATTACK disappears within the same turn)"
    )
    violations = [e for e in same_turn_continues if e["has_attack_after"]]
    assert violations == [], f"engine offered a second ATTACK within the same turn: {violations}"


def test_supporter_played_once_per_turn(corpus):
    """A Supporter card can be played only once per turn.

    Mined evidence: 889 real Supporter plays, every one flipping
    current.supporterPlayed from False to True, and in NONE of them was a
    second SUPPORTER-type PLAY option offered again within the same turn.
    """
    events = corpus["supporter_events"]
    assert events, "expected at least one real Supporter play in the mined corpus"

    for e in events:
        assert e["before"] is False and e["after"] is True, e

    violations = [e for e in events if e["still_offered_same_turn"]]
    assert violations == [], f"engine offered a second SUPPORTER play within the same turn: {violations}"
