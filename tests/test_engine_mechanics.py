def test_sleep_requires_coin_flip_to_wake(corpus):
    """Sleep resolves after a variable number of turns (a coin-flip wake-up check), not a fixed duration.

    NOTE ON DETERMINISM: driving the SAME replay-derived observation twice
    does not reproduce the same game -- the engine has genuine internal
    randomness (coin flips are not seeded by our inputs), confirmed by
    re-driving data/replays/83758507.json ten times and observing a
    different sequence of turns/sleep-episode-lengths every time. So this
    test pools sleep episodes across several independent drives of that
    replay (chosen because it reliably puts a Pokemon to sleep) rather than
    asserting on a single run.

    Pooled evidence (10 independent drives, <1s total): every drive produced
    at least one sleep episode that resolved in exactly 1 turn AND at least
    one that lasted 2+ turns. A fixed-duration status would show the same
    length every time; this variability is the coin-flip's signature. Every
    episode across all drives eventually resolved back to awake (the status
    is not permanent).
    """
    files = esd.replay_files()
    names = [f.name for f in files]
    target = "83758507.json"
    if target not in names:
        pytest.skip(f"expected replay {target} is not present in data/replays")

    import json
    with open(files[names.index(target)]) as f:
        replay = json.load(f)
    obs = esd.find_mid_game_obs(replay)
    if obs is None:
        pytest.skip(f"could not extract a mid-game observation from {target}")

    all_episode_lengths = []
    resolved_count = 0
    unresolved_count = 0
    for _trial in range(10):
        drv = esd.Driver.from_replay(obs)
        try:
            asleep_turns = []  # distinct turns where player 0's active was observed asleep
            for _ in range(150):
                if drv.game_over:
                    break
                cur = drv.current
                if cur.players[0].asleep and (not asleep_turns or asleep_turns[-1] != cur.turn):
                    asleep_turns.append(cur.turn)
                if not drv.advance():
                    break
            final_asleep = not drv.game_over and drv.current.players[0].asleep
        finally:
            drv.release()

        episode = []
        for t in asleep_turns:
            if episode and t == episode[-1] + 1:
                episode.append(t)
            else:
                if episode:
                    all_episode_lengths.append(len(episode))
                    resolved_count += 1
                episode = [t]
        if episode:
            if final_asleep:
                unresolved_count += 1  # still asleep when the drive stopped -- don't count as a "resolved" length
            else:
                all_episode_lengths.append(len(episode))
                resolved_count += 1

    assert resolved_count > 0, "expected at least one sleep episode to resolve back to awake across 10 drives"
    lengths = set(all_episode_lengths)
    assert lengths, "expected at least one measured sleep-episode length"
    assert 1 in lengths, f"expected at least one sleep episode resolving in exactly 1 turn, got {all_episode_lengths}"
    assert any(length > 1 for length in lengths), (
        f"a coin-flip wake-up check should also produce episodes lasting MORE than 1 turn "
        f"(a fixed 1-turn duration would not be a coin flip); got {all_episode_lengths}"
    )


